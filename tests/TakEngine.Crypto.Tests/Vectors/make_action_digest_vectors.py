"""Regenerates action-digest-vectors.json (F-033, D-041) with an implementation independent of the C# ActionDigest:
preimage = "tak/action/v1\n" + pv + "\n" + action_type + "\n" + game_id + "\n" + turn + "\n" + player_pubkey + "\n"
           + prev_state_hash + "\n" + json.dumps(action_data, separators=(",", ":"), sort_keys=True, ensure_ascii=False),
digest = sha256(UTF-8(preimage)), signature = bitcoin/bips BIP-340 reference (tests/TakEngine.Transport.Tests/Vectors/
bip340_reference.py) with a fixed aux per case, so the C# signature must match exactly.
Run from the repo root: python3 tests/TakEngine.Crypto.Tests/Vectors/make_action_digest_vectors.py"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "TakEngine.Transport.Tests", "Vectors"))
from bip340_reference import pubkey_gen, schnorr_sign, schnorr_verify  # noqa: E402

sk = hashlib.sha256(b"tak-p2p action digest vector key").digest()
pk = pubkey_gen(sk).hex()
other = pubkey_gen(hashlib.sha256(b"tak-p2p action digest vector other").digest()).hex()
game_id = "0b7e3d4c-1f2a-4b5c-8d9e-0f1a2b3c4d5e"
genesis = hashlib.sha256(b"genesis placeholder").hexdigest()
prev = hashlib.sha256(b"prev placeholder").hexdigest()
nonce_a = hashlib.sha256(b"guest nonce").hexdigest()
nonce_b = hashlib.sha256(b"host nonce").hexdigest()

cases = [
    ("join", "JOIN", 0, genesis, {"guest_nonce": nonce_a}),
    ("accept", "ACCEPT", 0, genesis, {"white": pk, "black": other, "host_nonce": nonce_b, "komi": 5, "size": 6}),
    ("move-place", "MOVE", 1, genesis, {"ptn": "a1"}),
    ("move-slide-specials", "MOVE", 17, prev, {"ptn": "3c3>12*"}),
    ("move-escaping", "MOVE", 2, prev, {"ptn": "a<b>&+\"q\"\\"}),
    ("resign", "RESIGN", 9, prev, {}),
]

out = {
    "_source": "Generated by make_action_digest_vectors.py (Python json + hashlib for the digest, bitcoin/bips bip340_reference.py for the signature).",
    "secret_key": sk.hex(),
    "pubkey": pk,
    "cases": [],
}
for i, (name, action_type, turn, prev_hash, data) in enumerate(cases):
    canonical = json.dumps(data, separators=(",", ":"), sort_keys=True, ensure_ascii=False)
    preimage = f"tak/action/v1\n1\n{action_type}\n{game_id}\n{turn}\n{pk}\n{prev_hash}\n{canonical}"
    digest = hashlib.sha256(preimage.encode("utf-8")).digest()
    aux = hashlib.sha256(f"aux {i}".encode()).digest()
    sig = schnorr_sign(digest, sk, aux)
    assert schnorr_verify(digest, bytes.fromhex(pk), sig)
    out["cases"].append({
        "name": name, "pv": 1, "action_type": action_type, "game_id": game_id, "turn": turn,
        "prev_state_hash": prev_hash, "action_data": data, "canonical_action_data": canonical,
        "preimage": preimage, "digest": digest.hex(), "aux": aux.hex(), "signature": sig.hex(),
    })

with open(os.path.join(HERE, "action-digest-vectors.json"), "w", encoding="utf-8", newline="\n") as f:
    json.dump(out, f, indent=2, ensure_ascii=False)
    f.write("\n")
